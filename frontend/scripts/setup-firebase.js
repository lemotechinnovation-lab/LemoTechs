#!/usr/bin/env node

/**
 * Firebase Setup Helper Script
 * 
 * This script helps you set up Firebase environment variables
 * Run with: node scripts/setup-firebase.js
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

const envPath = path.join(__dirname, '..', '.env');
const envExamplePath = path.join(__dirname, '..', 'env.example');

console.log('🔥 Firebase Environment Setup Helper\n');

// Check if .env already exists
if (fs.existsSync(envPath)) {
  console.log('⚠️  .env file already exists!');
  rl.question('Do you want to overwrite it? (y/N): ', (answer) => {
    if (answer.toLowerCase() === 'y' || answer.toLowerCase() === 'yes') {
      setupEnvironment();
    } else {
      console.log('Setup cancelled.');
      rl.close();
    }
  });
} else {
  setupEnvironment();
}

function setupEnvironment() {
  console.log('\n📝 Please provide your Firebase configuration details:');
  console.log('(You can find these in Firebase Console → Project Settings → General)\n');

  const questions = [
    {
      key: 'VITE_FIREBASE_API_KEY',
      prompt: 'Firebase API Key: ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_AUTH_DOMAIN',
      prompt: 'Firebase Auth Domain (e.g., your-project.firebaseapp.com): ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_PROJECT_ID',
      prompt: 'Firebase Project ID: ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_STORAGE_BUCKET',
      prompt: 'Firebase Storage Bucket (e.g., your-project.appspot.com): ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_MESSAGING_SENDER_ID',
      prompt: 'Firebase Messaging Sender ID: ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_APP_ID',
      prompt: 'Firebase App ID: ',
      required: true
    },
    {
      key: 'VITE_FIREBASE_MEASUREMENT_ID',
      prompt: 'Firebase Measurement ID (optional): ',
      required: false
    }
  ];

  const envVars = {};
  let currentIndex = 0;

  function askQuestion() {
    if (currentIndex >= questions.length) {
      writeEnvFile(envVars);
      return;
    }

    const question = questions[currentIndex];
    rl.question(question.prompt, (answer) => {
      if (question.required && !answer.trim()) {
        console.log('❌ This field is required!');
        askQuestion();
        return;
      }

      envVars[question.key] = answer.trim();
      currentIndex++;
      askQuestion();
    });
  }

  askQuestion();
}

function writeEnvFile(envVars) {
  console.log('\n📄 Writing .env file...');

  let envContent = '# Firebase Configuration\n';
  envContent += '# Generated by setup-firebase.js\n\n';

  Object.entries(envVars).forEach(([key, value]) => {
    if (value) {
      envContent += `${key}=${value}\n`;
    }
  });

  envContent += '\n# Development Settings\n';
  envContent += 'NODE_ENV=development\n';
  envContent += 'VITE_APP_ENV=development\n';

  try {
    fs.writeFileSync(envPath, envContent);
    console.log('✅ .env file created successfully!');
    
    // Also update env.example
    if (fs.existsSync(envExamplePath)) {
      fs.writeFileSync(envExamplePath, envContent.replace(/=.*$/gm, '=your_value_here'));
      console.log('✅ env.example updated!');
    }

    console.log('\n🎉 Setup complete!');
    console.log('\nNext steps:');
    console.log('1. Start your development server: npm run dev');
    console.log('2. Test the social login buttons');
    console.log('3. Check the browser console for any errors');
    console.log('\n📚 For detailed setup instructions, see: docs/FIREBASE_SOCIAL_AUTH_SETUP.md');

  } catch (error) {
    console.error('❌ Error writing .env file:', error.message);
  }

  rl.close();
}

// Handle Ctrl+C
rl.on('SIGINT', () => {
  console.log('\n\nSetup cancelled.');
  rl.close();
});
